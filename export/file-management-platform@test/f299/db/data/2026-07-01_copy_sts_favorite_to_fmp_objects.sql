PROMPT Copy STS favorite data into FMP tables for f299
DECLARE
    PROCEDURE copy_table(
        p_target_table IN VARCHAR2,
        p_source_table IN VARCHAR2
    ) IS
        l_columns VARCHAR2(32767);
    BEGIN
        SELECT LISTAGG(column_name, ',') WITHIN GROUP (ORDER BY column_id)
          INTO l_columns
          FROM user_tab_columns
         WHERE table_name = p_target_table
           AND column_name IN (
               SELECT column_name
                 FROM user_tab_columns
                WHERE table_name = p_source_table
           );

        EXECUTE IMMEDIATE 'DELETE FROM ' || p_target_table;
        EXECUTE IMMEDIATE
            'INSERT INTO ' || p_target_table || ' (' || l_columns || ') ' ||
            'SELECT ' || l_columns || ' FROM ' || p_source_table;
    END;
BEGIN
    copy_table('FMP_FAVORITE_GROUP', 'STS_FAVORITE_GROUP');
    copy_table('FMP_FAVORITE_FILE', 'STS_FAVORITE_FILE');

    EXECUTE IMMEDIATE 'ALTER TABLE FMP_FAVORITE_GROUP MODIFY FAVORITE_GROUP_ID GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE)';
    EXECUTE IMMEDIATE 'ALTER TABLE FMP_FAVORITE_FILE MODIFY FAVORITE_ID GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE)';

    COMMIT;
END;
/
