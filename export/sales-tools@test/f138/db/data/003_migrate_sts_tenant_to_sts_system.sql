set define off
whenever sqlerror exit sql.sqlcode rollback
whenever oserror exit failure rollback

declare
    v_table_count   number;
    v_column_count  number;
begin
    select count(*)
      into v_table_count
      from user_tables
     where table_name = 'STS_SYSTEM';

    if v_table_count = 0 then
        select count(*)
          into v_table_count
          from user_tables
         where table_name = 'STS_TENANT';

        if v_table_count = 1 then
            execute immediate 'rename STS_TENANT to STS_SYSTEM';
        else
            execute immediate q'[
                create table STS_SYSTEM
                (
                    SYSTEM_ID number(20,0) generated by default as identity,
                    SYSTEM_NAME varchar2(100) not null,
                    IS_ENABLE number(1,0) default 1,
                    DEL_FLAG number(1,0) default 0,
                    CREATED_BY number(20,0),
                    CREATION_DATE date default sysdate,
                    UPDATED_BY number(20,0),
                    UPDATE_DATE date default sysdate,
                    primary key (SYSTEM_ID)
                )
            ]';
        end if;
    end if;

    select count(*)
      into v_column_count
      from user_tab_cols
     where table_name = 'STS_SYSTEM'
       and column_name = 'TENANT_ID';
    if v_column_count = 1 then
        execute immediate 'alter table STS_SYSTEM rename column TENANT_ID to SYSTEM_ID';
    end if;

    select count(*)
      into v_column_count
      from user_tab_cols
     where table_name = 'STS_SYSTEM'
       and column_name = 'TENANT_NAME';
    if v_column_count = 1 then
        execute immediate 'alter table STS_SYSTEM rename column TENANT_NAME to SYSTEM_NAME';
    end if;
end;
/

merge into sts_system t
using (
    select 1 system_id, unistr('\9500\552E\5DE5\5177\96C6') system_name from dual
    union all
    select 2 system_id, unistr('\50A8\80FD\8D44\6599\5E93') system_name from dual
) s
on (t.system_id = s.system_id)
when matched then
    update set t.system_name = s.system_name,
               t.is_enable = 1,
               t.del_flag = 0,
               t.update_date = sysdate
when not matched then
    insert (
        system_id,
        system_name,
        is_enable,
        del_flag,
        created_by,
        creation_date,
        updated_by,
        update_date
    )
    values (
        s.system_id,
        s.system_name,
        1,
        0,
        -1,
        sysdate,
        -1,
        sysdate
    );

update sts_system
   set is_enable = 0,
       update_date = sysdate
 where system_id not in (1, 2);

commit;
